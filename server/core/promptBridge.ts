/**
 * Agent Prompt Bridge & Coding Tool Adapter (Upside-Down 2.0)
 * Generates tailored, ready-to-copy assignment prompts for multiple AI coding tools:
 * - Google Antigravity
 * - Claude Code
 * - OpenAI Codex
 * - Cursor
 * - Aider
 * - OpenCode
 */

import type {
  HackathonProject,
  ProjectIdea,
  ArchitectureBlueprint,
  TaskContractV2,
  SupportedCodingTool,
} from "../../contracts/hackathon.ts";

export class PromptBridgeService {
  /**
   * Generates a complete, structured prompt tailored to the specific coding tool
   */
  public generatePrompt(
    tool: SupportedCodingTool,
    project: HackathonProject,
    task: TaskContractV2,
    idea?: ProjectIdea | null,
    architecture?: ArchitectureBlueprint | null
  ): string {
    const toolName = this.formatToolName(tool);
    const branchName = `feat/${task.taskId.toLowerCase()}`;
    const allowed = task.allowedPaths.join(", ");
    const protectedPaths = task.protectedPaths.length > 0 ? task.protectedPaths.join(", ") : "None (all other paths protected by default)";

    const toolSpecific = this.getToolSpecificInstructions(tool, task, branchName, protectedPaths);

    return `# ASSIGNMENT DIRECTIVE FOR ${toolName.toUpperCase()}
# PROJECT: ${project.name}
# TASK: ${task.title} (ID: ${task.taskId})
# ASSIGNED ROLE: ${task.assignedRole.toUpperCase()}

## 1. PROJECT CONTEXT & VISION
- Problem Statement: "${project.problemStatement}"
- Selected Concept: ${idea ? `**${idea.name}** — ${idea.pitch}` : "Official Hackathon MVP"}
- Available Time: ${project.availableTime}
- Team Division: Developer Slot [${task.owner?.assignedSlot || "Unassigned"}] using ${toolName}

## 2. YOUR EXACT TASK OBJECTIVE
${task.objective}

## 3. STRICT PATH BOUNDARIES (DO NOT VIOLATE)
> [!IMPORTANT]
> To prevent collisions with sibling agents:
> - **ALLOWED PATHS (You may edit these)**: \`${allowed}\`
> - **PROTECTED PATHS (DO NOT MODIFY)**: \`${protectedPaths}\`

## 4. DELIVERABLES REQUIRED
${task.deliverables.map((d, i) => `${i + 1}. ${d}`).join("\n")}

## 5. ACCEPTANCE CRITERIA
${task.acceptanceCriteria.map((a, i) => `- [ ] ${a}`).join("\n")}

## 6. INPUT CONTRACTS & INTERFACES
${JSON.stringify(task.inputs, null, 2)}

## 7. GIT BRANCH & SUBMISSION INSTRUCTIONS
1. Create and switch to your isolated feature branch:
   \`git checkout -b ${branchName}\`
2. Implement the deliverables strictly inside your allowed paths.
3. Run local tests: \`npm test\` or \`npm run typecheck\`.
4. Commit your changes:
   \`git commit -m "feat(${task.assignedRole}): implement ${task.title}"\`
5. Push to origin:
   \`git push origin ${branchName}\`
6. Open a GitHub Pull Request and submit the PR URL / commit hash to Upside-Down Mission Control.

${toolSpecific}

---
*Generated by Upside-Down 2.0 AI Hackathon Mission Control — Protocol: UD-IC/2.0*
`;
  }

  private getToolSpecificInstructions(
    tool: SupportedCodingTool,
    task: TaskContractV2,
    branchName: string,
    protectedPaths: string
  ): string {
    const allowed = task.allowedPaths.join(", ");
    switch (tool) {
      case "antigravity":
        return `## 8. GOOGLE ANTIGRAVITY SPECIFIC INSTRUCTIONS
- Use \`run_command\` to run test and build verification.
- Use \`read_file\`, \`edit_file\`, and \`write_file\` to implement code strictly in: \`${allowed}\`.
- Do NOT touch protected files: \`${protectedPaths}\`.
- Store any scratch scripts in your conversation scratch directory.
- Verify tests exit with code 0 before concluding your task.`;

      case "claude-code":
        return `## 8. CLAUDE CODE CLI EXECUTION INSTRUCTIONS
- Recommended CLI invocation:
  \`\`\`bash
  claude -p "Implement task ${task.taskId}: ${task.title}. Edit only files in ${allowed}."
  \`\`\`
- Let Claude Code checkout \`${branchName}\`, read requirements, make isolated edits, and verify tests.
- Push the branch and submit the resulting PR link to Mission Control.`;

      case "cursor":
        return `## 8. CURSOR IDE & COMPOSER INSTRUCTIONS
- Copy this prompt into Cursor Composer (\`Ctrl+I\` / \`Cmd+I\`) in Agent Mode.
- Or save the following as \`.cursorrules\` in your project:
  \`\`\`markdown
  # CURSOR CONSTRAINTS FOR ${task.taskId}
  - Allowed files: ${allowed}
  - Protected files: ${protectedPaths}
  - Keep tests passing at all times.
  \`\`\``;

      case "aider":
        return `## 8. AIDER CLI EXECUTION INSTRUCTIONS
- Run Aider with allowed files preloaded:
  \`\`\`bash
  git checkout -b ${branchName}
  aider ${task.allowedPaths.map((p) => `"${p}"`).join(" ")}
  \`\`\`
- Paste this prompt directly into Aider. Aider will create atomic git commits.`;

      case "codex":
        return `## 8. OPENAI CODEX / API INSTRUCTIONS
- System prompt: "You are an autonomous coding specialist working on ${task.taskId}. Modify strictly ${allowed}."
- Ensure all types and API endpoints adhere strictly to the contracts.`;

      case "opencode":
        return `## 8. OPENCODE EXECUTION INSTRUCTIONS
- Launch OpenCode in terminal:
  \`\`\`bash
  opencode --task "${task.taskId}" --branch "${branchName}"
  \`\`\``;

      default:
        return `## 8. CODING ASSISTANT GUIDELINES
- Work strictly inside \`${allowed}\`.
- Do not modify \`${protectedPaths}\`.`;
    }
  }

  private formatToolName(tool: SupportedCodingTool): string {
    switch (tool) {
      case "antigravity":
        return "Google Antigravity";
      case "claude-code":
        return "Claude Code";
      case "codex":
        return "OpenAI Codex";
      case "cursor":
        return "Cursor";
      case "aider":
        return "Aider";
      case "opencode":
        return "OpenCode";
      default:
        return "AI Coding Assistant";
    }
  }
}
