/**
 * Agent Prompt Bridge & Coding Tool Adapter (Upside-Down 2.0)
 * Generates tailored, ready-to-copy assignment prompts for multiple AI coding tools:
 * - Google Antigravity
 * - Claude Code
 * - OpenAI Codex
 * - Cursor
 * - Aider
 * - OpenCode
 */

import type {
  HackathonProject,
  ProjectIdea,
  ArchitectureBlueprint,
  TaskContractV2,
  SupportedCodingTool,
} from "../../contracts/hackathon.ts";

export class PromptBridgeService {
  /**
   * Generates a complete, structured prompt tailored to the specific coding tool
   */
  public generatePrompt(
    tool: SupportedCodingTool,
    project: HackathonProject,
    task: TaskContractV2,
    idea?: ProjectIdea | null,
    architecture?: ArchitectureBlueprint | null
  ): string {
    const toolName = this.formatToolName(tool);
    const branchName = `feat/${task.taskId.toLowerCase()}`;
    const allowed = task.allowedPaths.join(", ");
    const protectedPaths = task.protectedPaths.length > 0 ? task.protectedPaths.join(", ") : "None (all other paths protected by default)";

    return `# ASSIGNMENT DIRECTIVE FOR ${toolName.toUpperCase()}
# PROJECT: ${project.name}
# TASK: ${task.title} (ID: ${task.taskId})
# ASSIGNED ROLE: ${task.assignedRole.toUpperCase()}

## 1. PROJECT CONTEXT & VISION
- Problem Statement: "${project.problemStatement}"
- Selected Concept: ${idea ? `**${idea.name}** — ${idea.pitch}` : "Official Hackathon MVP"}
- Available Time: ${project.availableTime}
- Team Division: Developer Slot [${task.owner?.assignedSlot || "Unassigned"}] using ${toolName}

## 2. YOUR EXACT TASK OBJECTIVE
${task.objective}

## 3. STRICT PATH BOUNDARIES (DO NOT VIOLATE)
> [!IMPORTANT]
> To prevent collisions with sibling agents:
> - **ALLOWED PATHS (You may edit these)**: \`${allowed}\`
> - **PROTECTED PATHS (DO NOT MODIFY)**: \`${protectedPaths}\`

## 4. DELIVERABLES REQUIRED
${task.deliverables.map((d, i) => `${i + 1}. ${d}`).join("\n")}

## 5. ACCEPTANCE CRITERIA
${task.acceptanceCriteria.map((a, i) => `- [ ] ${a}`).join("\n")}

## 6. INPUT CONTRACTS & INTERFACES
${JSON.stringify(task.inputs, null, 2)}

## 7. GIT BRANCH & SUBMISSION INSTRUCTIONS
1. Create and switch to your isolated feature branch:
   \`git checkout -b ${branchName}\`
2. Implement the deliverables strictly inside your allowed paths.
3. Run local tests: \`npm test\` or \`npm run typecheck\`.
4. Commit your changes:
   \`git commit -m "feat(${task.assignedRole}): implement ${task.title}"\`
5. Push to origin:
   \`git push origin ${branchName}\`
6. Open a GitHub Pull Request and submit the PR URL / commit hash to Upside-Down Mission Control.

---
*Generated by Upside-Down 2.0 AI Hackathon Mission Control — Protocol: UD-IC/2.0*
`;
  }

  private formatToolName(tool: SupportedCodingTool): string {
    switch (tool) {
      case "antigravity":
        return "Google Antigravity";
      case "claude-code":
        return "Claude Code";
      case "codex":
        return "OpenAI Codex";
      case "cursor":
        return "Cursor";
      case "aider":
        return "Aider";
      case "opencode":
        return "OpenCode";
      default:
        return "AI Coding Assistant";
    }
  }
}
