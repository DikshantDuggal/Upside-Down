import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { chromium, expect } from '../web/node_modules/@playwright/test/index.mjs';
const root = path.resolve(import.meta.dirname, '..');
const state = path.resolve(process.env.UD_ACCEPTANCE_STATE ?? process.env.UD_STATE_DIR ?? path.join(process.env.LOCALAPPDATA ?? process.env.XDG_STATE_HOME ?? root, 'UpsideDown', 'final-mvp'));
const runtime = fs.existsSync(path.join(state, 'launch-control.json')) ? JSON.parse(fs.readFileSync(path.join(state, 'launch-control.json'), 'utf8')).urls : undefined;
const origin = process.env.UD_ACCEPTANCE_ORIGIN ?? runtime?.web ?? 'http://127.0.0.1:5173';
const coordinator = process.env.UD_ACCEPTANCE_COORDINATOR ?? runtime?.coordinator ?? 'http://127.0.0.1:4000';
const credential = fs.readFileSync(path.join(state, 'device.token'), 'utf8').trim();
const pairingKey = JSON.parse(fs.readFileSync(path.join(state, 'device.db.session.json'), 'utf8')).pairingKey;
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage(); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin);
  await page.getByRole('button', { name: 'Pair browser', exact: true }).click();
  await page.getByLabel('Local pairing key', { exact: true }).fill(pairingKey);
  await page.getByRole('dialog').getByRole('button', { name: 'Pair browser', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const title = `LAUNCH ACCEPTANCE ${randomUUID()}`;
  await page.getByRole('button', { name: 'New task', exact: true }).click();
  await page.getByRole('textbox', { name: 'Task title' }).fill(title);
  await page.getByRole('button', { name: 'Queue task', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('link', { name: 'Tasks', exact: true }).click();
  await expect(page.getByText(title, { exact: true }).first()).toBeVisible({ timeout: 20000 });
  const headers = { Authorization: `Bearer ${credential}`, 'X-UD-Contract': 'UD-IC/1.0' };
  const tasks = await fetch(coordinator + '/api/tasks', { headers }).then(r => r.json());
  assert.equal(tasks.filter(task => task.title === title).length, 1);
  await page.reload(); await expect(page.getByText(title, { exact: true }).first()).toBeVisible();
  await page.getByRole('link', { name: 'Team messages', exact: true }).click();
  const message = `Real LAN transport acceptance ${randomUUID()}`;
  await page.getByLabel('Message your team').fill(message);
  await page.getByRole('button', { name: 'Queue message', exact: true }).click();
  await expect(page.locator('article.message').filter({ hasText: message })).toBeVisible({ timeout: 20000 });
  const events = await fetch(coordinator + '/api/events?limit=200', { headers }).then(r => r.json());
  assert.equal(events.filter(event => event.payload?.message?.text === message).length, 1);
  await page.reload();
  await expect(page.locator('article.message').filter({ hasText: message })).toBeVisible({ timeout: 20000 });
  const stored = await page.evaluate(() => JSON.stringify(localStorage));
  assert.ok(!stored.includes(pairingKey) && !stored.includes(credential));
  assert.deepEqual(errors, []);
  fs.mkdirSync(path.join(root, '.board/evidence'), { recursive: true });
  await page.screenshot({ path: path.join(root, '.board/evidence/official-live.png'), fullPage: true });
  fs.writeFileSync(path.join(root, '.board/evidence/live-browser.json'), JSON.stringify({ passed: true, timestamp: new Date().toISOString(), origin, coordinator, taskId: tasks.find(task => task.title === title).id, assertions: ['official built frontend loaded','actual browser pairing','task durable delivery','one authoritative task','reload persisted task','message delivered and live UI updated','no stored credentials','no browser page errors'] }, null, 2));
  console.log('PASS: official built frontend, pairing, actual durable task/message delivery, live UI updates, reload and credential isolation.');
} finally { await browser.close(); }
